-- ==========================================================================
-- Проект: SQL-запросы для анализа продаж Northwind
-- 
-- Описание:
-- Этот файл содержит SQL-запросы для анализа базы данных Northwind.
-- Запросы сгруппированы по задачам:
--   - Запросы 1-4: Анализ товаров (ассортимент, цены, складские запасы)
--   - Запросы 5-6: Анализ клиентов (география, поиск по названию)
--   - Запрос 7: Категоризация товаров по цене
--   - Запросы 8-9: Текстовый поиск и расчёт выручки
--   - Запросы 10-11: Работа с пропусками и датами
--   - Запросы 12-13: Уникальные значения и группировка
-- ==========================================================================

-- ==========================================================================
-- ЗАПРОС 1: Показать все товары
-- ==========================================================================

SELECT *
FROM products
LIMIT 10;

-- ==========================================================================
-- ЗАПРОС 2: Топ-10 самых дорогих товаров
-- ==========================================================================

SELECT 
    product_name,
    unit_price,
    units_in_stock
FROM products
ORDER BY unit_price DESC
LIMIT 10;

-- ==========================================================================
-- ЗАПРОС 3: Товары дешевле $20
-- ==========================================================================

SELECT 
    product_name,
    unit_price,
    units_in_stock
FROM products
WHERE unit_price < 20
ORDER BY unit_price ASC;

-- ==========================================================================
-- ЗАПРОС 4: Товары, которых мало на складе (меньше 20 штук)
-- ==========================================================================

SELECT 
    product_name,
    units_in_stock,
    unit_price
FROM products
WHERE units_in_stock < 20
ORDER BY units_in_stock ASC;

-- ==========================================================================
-- ЗАПРОС 5: Клиенты из Германии
-- ==========================================================================

SELECT 
    company_name,
    contact_name,
    city,
    country
FROM customers
WHERE country = 'Germany'
ORDER BY company_name;

-- ==========================================================================
-- ЗАПРОС 6: Найти клиентов с "Restaurant" в названии
-- ==========================================================================

SELECT 
    company_name,
    city,
    country
FROM customers
WHERE company_name ILIKE '%Restaurant%'
ORDER BY company_name;

-- ==========================================================================
-- ЗАПРОС 7: Категоризация товаров по цене
-- ==========================================================================

SELECT 
    product_name,
    unit_price,
    CASE 
        WHEN unit_price > 100 THEN 'Премиум'
        WHEN unit_price > 50 THEN 'Средний'
        ELSE 'Бюджетный'
    END AS price_category
FROM products
ORDER BY unit_price DESC;

-- ==========================================================================
-- ЗАПРОС 8: Товары, название которых начинается на "C"
-- ==========================================================================

SELECT 
    product_name,
    unit_price
FROM products
WHERE product_name LIKE 'C%'
ORDER BY product_name;

-- ==========================================================================
-- ЗАПРОС 9: Посчитать потенциальную выручку от каждого товара
-- ==========================================================================

SELECT 
    product_name,
    unit_price,
    units_in_stock,
    unit_price * units_in_stock AS potential_revenue
FROM products
WHERE units_in_stock > 0
ORDER BY potential_revenue DESC
LIMIT 10;

-- ==========================================================================
-- ЗАПРОС 10: Клиенты без факса (пропущенные данные)
-- ==========================================================================

SELECT 
    company_name,
    phone,
    fax
FROM customers
WHERE fax IS NULL
ORDER BY company_name
LIMIT 10;

-- ==========================================================================
-- ЗАПРОС 11: Показать все заказы, сделанные в мае (любого года)
-- ==========================================================================

SELECT 
    order_id,
    order_date,
    customer_id
FROM orders
WHERE EXTRACT(MONTH FROM order_date) = 5
ORDER BY order_date;

-- ==========================================================================
-- ЗАПРОС 12: Уникальные страны клиентов
-- ==========================================================================

SELECT DISTINCT country
FROM customers
ORDER BY country;

-- ==========================================================================
-- ЗАПРОС 13: Сколько клиентов в каждой стране (базовая группировка)
-- ==========================================================================

SELECT 
    country,
    COUNT(*) AS customer_count
FROM customers
GROUP BY country
ORDER BY customer_count DESC;
